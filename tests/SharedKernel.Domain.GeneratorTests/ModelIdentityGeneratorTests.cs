namespace SharedKernel.Domain.GeneratorTests;

/// <summary>Tests that the model identity generator emits Equals and GetHashCode for opted-in partial classes and reports SKMDL001 to SKMDL009 for unsupported shapes.</summary>
[Trait(Testing.TestTraitNames.CapabilityName, TestTraits.IdentityCapability)]
public sealed class ModelIdentityGeneratorTests
{
    [Fact]
    public void Generates_identity_equality_for_opted_in_identified_partial_class()
    {
        // Arrange
        const string source = """
            namespace Demo;

            [GenerateModelSupport(Identity = true)]
            public sealed partial class Customer : IIdentified<int>
            {
                public int Id { get; private init; }
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult, "Demo.Customer.ModelSupport.g.cs");

        // Assert
        generatedSource.ShouldContain("// <auto-generated />", StringComparison.Ordinal);
        generatedSource.ShouldContain("namespace Demo;", StringComparison.Ordinal);
        generatedSource.ShouldContain("public partial class Customer", StringComparison.Ordinal);
        generatedSource.ShouldContain("public override bool Equals(object? obj)", StringComparison.Ordinal);
        generatedSource.ShouldContain("obj is not Customer other", StringComparison.Ordinal);
        generatedSource.ShouldContain("GetType() != other.GetType()", StringComparison.Ordinal);
        generatedSource.ShouldContain(".Default.Equals(Id, default!)", StringComparison.Ordinal);
        generatedSource.ShouldContain("public override int GetHashCode()", StringComparison.Ordinal);
    }

    [Fact]
    public void Generates_default_safe_hash_code_for_reference_type_identity()
    {
        // Arrange
        const string source = """
            #nullable enable

            namespace Demo;

            [GenerateModelSupport(Identity = true)]
            public sealed partial class Customer : IIdentified<string>
            {
                public string Id { get; private init; } = null!;
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var outputCompilation = GeneratorTestHarness.RunGeneratorAndUpdateCompilation(compilation, out var runResult);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult, "Demo.Customer.ModelSupport.g.cs");
        var errors = outputCompilation.GetDiagnostics(TestContext.Current.CancellationToken)
            .Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
