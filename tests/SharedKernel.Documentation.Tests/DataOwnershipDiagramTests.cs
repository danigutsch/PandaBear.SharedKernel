namespace PandaBear.Documentation.Tests;

/// <summary>Exercises typed data ownership generation, stable ordering and check-only drift detection.</summary>
[Trait(Testing.TestTraitNames.CapabilityName, TestTraits.DocumentationGenerationCapability)]
[Trait(Testing.TestTraitNames.CategoryName, TestTraits.CoreBehaviorCategory)]
public sealed class DataOwnershipDiagramTests
{
    [Fact]
    public void Updates_a_venue_diagram_through_the_existing_markers()
    {
        // Arrange
        using var workspace = new TemporaryDocumentationWorkspace();
        workspace.WriteArchitectureDoc("ownership.md", """
            # Venue operations

            <!-- generated:ownership:start -->
            stale
            <!-- generated:ownership:end -->
            """);
        var diagram = new DataOwnershipDiagram(
            [new("venue", "Venue operations"), new("data", "Records & scheduling"), new("vacant", "Unused")],
            [new("WelcomeDesk", "venue", ["Welcome desk"]), new("Schedule", "venue", ["Public schedule"])],
            [new("RoomLedger", "data", ["Room ledger", "Rooms <reservations>"])],
            [new("WelcomeDesk", "RoomLedger", "records \"requests\""), new("Schedule", "RoomLedger", "reads")]);

        // Act
        var stale = DocumentationGenerator.RunDataOwnership(workspace.RootPath, "docs/architecture", "Venue.Tool",
            "ownership", "ownership.md", diagram, checkOnly: true);
        var before = workspace.ReadArchitectureDoc("ownership.md");
        var updated = DocumentationGenerator.RunDataOwnership(workspace.RootPath, "docs/architecture", "Venue.Tool",
            "ownership", "ownership.md", diagram, checkOnly: false);
        var rendered = workspace.ReadArchitectureDoc("ownership.md");
        var current = DocumentationGenerator.RunDataOwnership(workspace.RootPath, "docs/architecture", "Venue.Tool",
            "ownership", "ownership.md", diagram, checkOnly: true);

        // Assert
        stale.ChangedFiles.ShouldBe(["docs/architecture/ownership.md"]);
        before.ShouldContain("stale", StringComparison.Ordinal);
        updated.ChangedFiles.ShouldBe(["docs/architecture/ownership.md"]);
        current.ChangedFiles.ShouldBeEmpty();
        rendered.ShouldContain("""
            <!-- Generated by Venue.Tool. Do not edit by hand. -->

            ```mermaid
            flowchart LR
                subgraph boundary_data["Records &amp; scheduling"]
                    RoomLedger["Room ledger<br/>Rooms &lt;reservations&gt;"]
                end
                subgraph boundary_venue["Venue operations"]
                    Schedule["Public schedule"]
                    WelcomeDesk["Welcome desk"]
                end
                Schedule -->|"reads"| RoomLedger
                WelcomeDesk -->|"records &quot;requests&quot;"| RoomLedger
            ```
            """, StringComparison.Ordinal);
    }
}
