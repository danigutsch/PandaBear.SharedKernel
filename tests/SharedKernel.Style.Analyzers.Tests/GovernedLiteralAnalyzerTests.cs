using Microsoft.CodeAnalysis;

namespace PandaBear.Style.Analyzers.Tests;

public sealed class GovernedLiteralAnalyzerTests
{
    [Theory]
    [InlineData("ASPNETCORE_ENVIRONMENT")]
    [InlineData("DOTNET_ENVIRONMENT")]
    [InlineData("MalwareScanning:ClamAv")]
    [InlineData("MalwareScanning:Disabled")]
    [InlineData("MalwareScanning:ClamAv:Host")]
    [InlineData("MalwareScanning:ClamAv:Port")]
    [InlineData("MalwareScanning:ClamAv:Timeout")]
    [InlineData("MalwareScanning:ClamAv:ChunkSize")]
    public async Task Registered_literal_reports_canonical_replacement(string value)
    {
        var catalog = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "GovernedLiterals.txt"), TestContext.Current.CancellationToken);
        var owner = GovernedLiteralCatalog.Parse(catalog).Single(entry => entry.Value == value);
        var diagnostics = await GovernedLiteralTestHarness.Analyze($"class Consumer {{ string Read() => \"{value}\"; }}", catalog);
        var diagnostic = diagnostics.Where(d => d.Id == "SKSTYLE012").ShouldHaveSingleItem();
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldContain(owner.Symbol, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("class Consumer { string Read() => \"unrelated\"; }")]
    [InlineData("namespace Demo; public static class Keys { public const string Value = \"registered\"; }")]
    [InlineData("namespace Demo; public static class Keys { public const string Value = \"reg\" + \"istered\"; }")]
    public async Task Unrelated_strings_and_canonical_declarations_are_allowed(string source)
    {
        (await GovernedLiteralTestHarness.Analyze(source, "registered|Production|Demo.Keys.Value"))
            .ShouldNotContain(d => d.Id == "SKSTYLE012");
    }

    [Fact]
    public async Task Only_exact_field_is_exempt_in_owner_type()
    {
        var source = "namespace Demo; public static class Keys { public const string Value = \"registered\"; public const string Duplicate = \"registered\"; }";
        (await GovernedLiteralTestHarness.Analyze(source, "registered|Production|Demo.Keys.Value"))
            .Count(d => d.Id == "SKSTYLE012").ShouldBe(1);
    }

    [Fact]
    public async Task Owner_name_in_wrong_assembly_is_not_exempt()
    {
        var source = "namespace Demo; public static class Keys { public const string Value = \"registered\"; }";
        (await GovernedLiteralTestHarness.Analyze(source, "registered|OtherAssembly|Demo.Keys.Value"))
            .ShouldContain(d => d.Id == "SKSTYLE012");
    }

    [Fact]
    public async Task Generated_code_and_absent_catalog_are_exempt()
    {
        (await GovernedLiteralTestHarness.Analyze("// <auto-generated/>\nclass Consumer { string Read() => \"registered\"; }", "registered|Production|Demo.Keys.Value"))
            .ShouldNotContain(d => d.Id == "SKSTYLE012");
        (await GovernedLiteralTestHarness.Analyze("class Consumer { string Read() => \"registered\"; }", null))
            .ShouldNotContain(d => d.Id == "SKSTYLE012");
    }

    [Theory]
    [InlineData("@\"registered\"")]
    [InlineData("\"\"\"registered\"\"\"")]
    [InlineData("\"reg\\u0069stered\"")]
    public async Task Equivalent_literal_spellings_are_reported(string expression)
    {
        (await GovernedLiteralTestHarness.Analyze($"class Consumer {{ string Read() => {expression}; }}", "registered|Production|Demo.Keys.Value"))
            .ShouldContain(d => d.Id == "SKSTYLE012");
    }

    [Fact]
    public async Task Canonical_symbol_references_and_unregistered_routes_are_allowed()
    {
        const string source = "namespace Demo; public static class Keys { public const string Value = \"registered\"; public static string Read() => Value; public const string Route = \"/registered\"; }";
        (await GovernedLiteralTestHarness.Analyze(source, "registered|Production|Demo.Keys.Value"))
            .ShouldNotContain(d => d.Id == "SKSTYLE012");
    }

    [Theory]
    [InlineData("broken")]
    [InlineData("registered|Production|Demo.Keys.Value\nregistered|Production|Demo.Keys.Other")]
    public async Task Invalid_catalog_reports_configuration_error(string catalog)
    {
        (await GovernedLiteralTestHarness.Analyze("class Consumer {}", catalog)).ShouldContain(d => d.Id == "SKSTYLE013");
    }

}
