using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace PandaBear.Style.Analyzers.Tests;

internal static class GovernedConstantGuard
{
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".generated.cs", ".designer.cs"];
    public static IReadOnlyList<string> Validate(IEnumerable<Compilation> compilations, string catalogText)
    {
        var catalog = GovernedLiteralCatalog.Parse(catalogText);
        var fields = new List<IFieldSymbol>();
        var errors = new List<string>();
        foreach (var compilation in compilations)
        {
            foreach (var tree in compilation.SyntaxTrees)
            {
                if (GeneratedSuffixes.Any(suffix => tree.FilePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
                    || tree.GetRoot().GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                var model = compilation.GetSemanticModel(tree);
                foreach (var declaration in tree.GetRoot().DescendantNodes().OfType<VariableDeclaratorSyntax>())
                {
                    var symbol = model.GetDeclaredSymbol(declaration);
                    if (symbol is not IFieldSymbol { IsConst: true, Type.SpecialType: SpecialType.System_String }
                        and not ILocalSymbol { IsConst: true, Type.SpecialType: SpecialType.System_String })
                    {
                        continue;
                    }

                    var generated = false;
                    for (var containing = symbol; containing is not null; containing = containing.ContainingSymbol)
                    {
                        if (containing.GetAttributes().Any(attribute =>
                            attribute.AttributeClass?.ToDisplayString() == "System.CodeDom.Compiler.GeneratedCodeAttribute"))
                        {
                            generated = true;
                            break;
                        }
                    }

                    if (generated)
                    {
                        continue;
                    }

                    if (symbol is IFieldSymbol field)
                    {
                        fields.Add(field);
                        if (!field.HasConstantValue)
                        {
                            errors.Add($"Cannot resolve constant {field} in {tree.FilePath}; uniqueness cannot be established.");
                        }
                    }
                    else if (symbol is ILocalSymbol local)
                    {
                        if (!local.HasConstantValue)
                        {
                            errors.Add($"Cannot resolve constant {local} in {tree.FilePath}; uniqueness cannot be established.");
                        }
                        else if (local.ConstantValue is string value && catalog.Any(entry => entry.Justification is null && entry.Value == value))
                        {
                            errors.Add($"Duplicate or redirected governed local constant {local.Name} in {tree.FilePath} = {value}.");
                        }
                    }
                }
            }
        }

        foreach (var entry in catalog)
        {
            var matches = fields.Where(field => GovernedLiteralCatalog.Matches(entry, field)).ToArray();
            if (matches.Length != 1 || !Equals(matches[0].ConstantValue, entry.Value))
            {
                errors.Add($"Expected exactly one const string {entry.Assembly}:{entry.Symbol} = {entry.Value}.");
            }
        }

        foreach (var field in fields)
        {
            if (field.ConstantValue is string value
                && catalog.Any(entry => entry.Justification is null && entry.Value == value)
                && !catalog.Any(entry => entry.Value == value && GovernedLiteralCatalog.Matches(entry, field)))
            {
                errors.Add($"Duplicate or redirected governed constant {field.ContainingAssembly.Name}:{field} = {value}.");
            }
        }

        return errors;
    }
}
