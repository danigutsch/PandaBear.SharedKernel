using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using SharedKernel.Testing.SourceGenerator;
using SharedHarness = SharedKernel.Testing.Roslyn.GeneratorTestHarness;

namespace SharedKernel.Testing.GeneratorTests;

/// <summary>Tests the source the CallProxy generator emits for a wrapped interface.</summary>
public sealed class CallProxyGeneratorOutputTests
{
    private const string CustomerStore = """
        namespace Demo;

        public sealed record Customer(string Email);

        public interface ICustomerStore
        {
            Task<Customer?> Find(Guid id, CancellationToken ct);

            Task<bool> EmailExists(string email, CancellationToken ct);

            void Add(Customer customer);
        }

        """;

    [Fact]
    public void Generates_the_proxy_the_typed_hooks_and_the_registration_of_a_wrapped_interface()
    {
        // Arrange
        var compilation = GeneratorTestHarness.CreateCompilation(CustomerStore + """
            public static class Setup
            {
                public static ICustomerStore Wrap(ICustomerStore store) =>
                    CallProxy.Create<ICustomerStore>(store, hooks => hooks.EmailExists.Returns(false));
            }
            """);

        // Act
        var runResult = GeneratorTestHarness.Run(compilation);

        // Assert
        GeneratorTestHarness.GetHintNames(runResult).ShouldBe(["CallProxy.Demo_ICustomerStore.g.cs"]);
        GeneratorTestHarness.GetGeneratedSource(runResult, "CallProxy.Demo_ICustomerStore.g.cs").ShouldBe("""
            // <auto-generated />
            #nullable enable

            namespace SharedKernel.Testing
            {
                /// <summary>The typed CallProxy hooks and proxy generated for <c>ICustomerStore</c>.</summary>
                internal static class CallProxyFor_Demo_ICustomerStore
                {
                    extension(global::SharedKernel.Testing.CallHooks<global::Demo.ICustomerStore> hooks)
                    {
                        /// <summary>Gets the hooks of <c>ICustomerStore.Find(Guid, CancellationToken)</c>.</summary>
                        public global::SharedKernel.Testing.MethodHooks<FindCall, global::Demo.Customer?> Find => hooks.Generated<HookSet>().Hooks0;

                        /// <summary>Gets the hooks of <c>ICustomerStore.EmailExists(string, CancellationToken)</c>.</summary>
                        public global::SharedKernel.Testing.MethodHooks<EmailExistsCall, bool> EmailExists => hooks.Generated<HookSet>().Hooks1;

                        /// <summary>Gets the hooks of <c>ICustomerStore.Add(Customer)</c>.</summary>
                        public global::SharedKernel.Testing.MethodHooks<AddCall> Add => hooks.Generated<HookSet>().Hooks2;
                    }

                    /// <summary>Registers the generated hooks, so a proxy without hooks can be created too.</summary>
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void Register() => global::SharedKernel.Testing.CallProxy.Register<global::Demo.ICustomerStore>(static () => new HookSet());

                    /// <summary>One call of <c>ICustomerStore.Find(Guid, CancellationToken)</c>.</summary>
                    internal sealed class FindCall
                    {
                        internal FindCall(global::System.Guid id, global::System.Threading.CancellationToken ct)
                        {
                            Id = id;
                            Ct = ct;
                        }

                        /// <summary>Gets the <c>id</c> argument.</summary>
                        public global::System.Guid Id { get; }

                        /// <summary>Gets the <c>ct</c> argument.</summary>
                        public global::System.Threading.CancellationToken Ct { get; }

                        /// <summary>Gets the result; set before the after hooks run.</summary>
                        public global::Demo.Customer? Result { get; internal set; } = default!;
                    }

                    /// <summary>One call of <c>ICustomerStore.EmailExists(string, CancellationToken)</c>.</summary>
                    internal sealed class EmailExistsCall
                    {
                        internal EmailExistsCall(string email, global::System.Threading.CancellationToken ct)
                        {
                            Email = email;
                            Ct = ct;
                        }

                        /// <summary>Gets the <c>email</c> argument.</summary>
                        public string Email { get; }

                        /// <summary>Gets the <c>ct</c> argument.</summary>
                        public global::System.Threading.CancellationToken Ct { get; }

                        /// <summary>Gets the result; set before the after hooks run.</summary>
                        public bool Result { get; internal set; } = default!;
                    }

                    /// <summary>One call of <c>ICustomerStore.Add(Customer)</c>.</summary>
                    internal sealed class AddCall
                    {
                        internal AddCall(global::Demo.Customer customer)
                        {
                            Customer = customer;
                        }

                        /// <summary>Gets the <c>customer</c> argument.</summary>
                        public global::Demo.Customer Customer { get; }
                    }

                    /// <summary>The hooks of every method of <c>ICustomerStore</c>.</summary>
                    internal sealed class HookSet : global::SharedKernel.Testing.GeneratedCallHooks<global::Demo.ICustomerStore>
                    {
                        internal readonly global::SharedKernel.Testing.MethodHooks<FindCall, global::Demo.Customer?> Hooks0 = new();

                        internal readonly global::SharedKernel.Testing.MethodHooks<EmailExistsCall, bool> Hooks1 = new();

                        internal readonly global::SharedKernel.Testing.MethodHooks<AddCall> Hooks2 = new();

                        /// <inheritdoc />
                        protected override global::Demo.ICustomerStore Wrap(global::Demo.ICustomerStore inner) => new Proxy(inner, this);
                    }

                    private sealed class Proxy : global::Demo.ICustomerStore
                    {
                        private readonly global::Demo.ICustomerStore __inner;
                        private readonly HookSet __hooks;

                        internal Proxy(global::Demo.ICustomerStore inner, HookSet hooks)
                        {
                            __inner = inner;
                            __hooks = hooks;
                        }

                        async global::System.Threading.Tasks.Task<global::Demo.Customer?> global::Demo.ICustomerStore.Find(global::System.Guid id, global::System.Threading.CancellationToken ct)
                        {
                            var __call = new FindCall(id, ct);
                            await __hooks.Hooks0.RunBefore(__call).ConfigureAwait(false);
                            __call.Result = __hooks.Hooks0.TryGetReplacement(out var __replacement)
                                ? __replacement
                                : await __inner.Find(id, ct).ConfigureAwait(false);
                            await __hooks.Hooks0.RunAfter(__call).ConfigureAwait(false);
                            return __call.Result;
                        }

                        async global::System.Threading.Tasks.Task<bool> global::Demo.ICustomerStore.EmailExists(string email, global::System.Threading.CancellationToken ct)
                        {
                            var __call = new EmailExistsCall(email, ct);
                            await __hooks.Hooks1.RunBefore(__call).ConfigureAwait(false);
                            __call.Result = __hooks.Hooks1.TryGetReplacement(out var __replacement)
                                ? __replacement
                                : await __inner.EmailExists(email, ct).ConfigureAwait(false);
                            await __hooks.Hooks1.RunAfter(__call).ConfigureAwait(false);
                            return __call.Result;
                        }

                        void global::Demo.ICustomerStore.Add(global::Demo.Customer customer)
                        {
                            var __call = new AddCall(customer);
                            __hooks.Hooks2.RunBefore(__call).GetAwaiter().GetResult();
                            __inner.Add(customer);
                            __hooks.Hooks2.RunAfter(__call).GetAwaiter().GetResult();
                        }
                    }
                }
            }

            """);
    }

    [Fact]
    public void Generated_code_compiles_cleanly_for_every_supported_method_shape()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public interface IBase
            {
                Task<int> Inherited();
            }

            internal interface IThing : IBase
            {
                void Touch();

                int Add(int left, int right);

                Task Run(CancellationToken cancellationToken);

                ValueTask Pause();

                Task<string?> FindName(string @event, int result);

                ValueTask<int?> FindNumber(params int[] values);

                Task Save();

                Task<int> Save(int value);

                Task<int> Save(List<Guid> ids);

                string Generated();

                Task Thing(int thingCall, int value, int Value);

                ValueTask<IReadOnlyList<int>> List(IEnumerable<int> items);

                int Implemented() => 1;
            }

            public interface ILeft
            {
                void Ping();
            }

            public interface IRight
            {
                void Ping();
            }

            internal interface IBoth : ILeft, IRight
            {
            }

            internal interface IRepository<T>
            {
                Task<T?> Find(Guid id);
            }

            public static class Container
            {
                public interface INested
                {
                    void Ping();
                }
            }

            internal static class Usage
            {
                internal static IThing Wrap(IThing thing) => CallProxy.Create(thing, hooks =>
                {
                    hooks.Touch.Before(_ => { });
                    hooks.Add.Returns(3).After(call => Console.WriteLine(call.Left + call.Right + call.Result));
                    hooks.Run.Before(call => Task.Delay(1, call.CancellationToken));
                    hooks.Pause.After(_ => Task.CompletedTask);
                    hooks.FindName.Returns(null).Before(call => Console.WriteLine(call.Event + call.ResultArgument));
                    hooks.FindNumber.Returns(7).After(call => Console.WriteLine(call.Values.Length));
                    hooks.Save_NoParameters.Before(_ => { });
                    hooks.Save_Int32.Returns(1);
                    hooks.Save_ListGuid.Returns(2);
                    hooks.GeneratedMethod.Returns("generated");
                    hooks.Thing.Before(call => Console.WriteLine(call.ThingCallArgument + call.Value + call.ValueArgument));
                    hooks.List.Returns([]);
                    hooks.Implemented.Returns(2);
                    hooks.Inherited.Returns(4);
                });

                internal static IBoth Wrap(IBoth both) => CallProxy.Create(both, hooks =>
                {
                    hooks.Ping_NoParameters.Before(_ => { });
                    hooks.Ping_NoParameters_2.After(_ => { });
                });

                internal static IRepository<string> Wrap(IRepository<string> repository) =>
                    CallProxy.Create(repository, hooks => hooks.Find.Returns("found"));

                internal static IServiceCollection Wrap(IServiceCollection services) =>
                    services.WrapWithCallProxy<Container.INested>(hooks => hooks.Ping.After(_ => { }));
            }
            """;

        // Act
        var diagnostics = GeneratorTestHarness.Compile(source, out var runResult);

        // Assert
        diagnostics.ShouldBeEmpty();
        GeneratorTestHarness.GetHintNames(runResult).ShouldBe(
        [
            "CallProxy.Demo_Container_INested.g.cs",
            "CallProxy.Demo_IBoth.g.cs",
            "CallProxy.Demo_IRepository_string.g.cs",
            "CallProxy.Demo_IThing.g.cs",
        ]);
    }

    [Theory]
    [InlineData("hooks.EmailExists.Returns(\"no\")", "CS1503")]
    [InlineData("hooks.Find.Returns(1)", "CS1503")]
    [InlineData("hooks.Add.Returns(null)", "CS1061")]
    [InlineData("hooks.Missing.Before(_ => { })", "CS1061")]
    [InlineData("hooks.Find.After(call => Console.WriteLine(call.Email))", "CS1061")]
    public void A_hook_that_does_not_fit_the_method_is_a_compile_error(string hook, string expectedError)
    {
        // Arrange
        var source = CustomerStore + $$"""
            public static class Setup
            {
                public static ICustomerStore Wrap(ICustomerStore store) => CallProxy.Create(store, hooks => {{hook}});
            }
            """;

        // Act
        var diagnostics = GeneratorTestHarness.Compile(source, out _);

        // Assert
        diagnostics.ShouldHaveSingleItem().Id.ShouldBe(expectedError);
    }

    [Fact]
    public void The_result_and_the_arguments_of_a_hook_are_typed()
    {
        // Arrange
        var source = CustomerStore + """
            public static class Setup
            {
                public static ICustomerStore Wrap(ICustomerStore store) => CallProxy.Create(store, hooks =>
                {
                    hooks.Find.After(call =>
                    {
                        Customer? customer = call.Result;
                        Guid id = call.Id;
                        CancellationToken token = call.Ct;
                        Console.WriteLine($"{customer?.Email} {id} {token.IsCancellationRequested}");
                    });
                    hooks.EmailExists.Before(call => Console.WriteLine(call.Email.Length));
                });
            }
            """;

        // Act
        var diagnostics = GeneratorTestHarness.Compile(source, out _);

        // Assert
        diagnostics.ShouldBeEmpty();
    }

    [Theory]
    [InlineData("public static IServiceCollection Wrap(IServiceCollection services) => services.WrapWithCallProxy<ICustomerStore>(_ => { });")]
    [InlineData("public static IServiceCollection Wrap(IServiceCollection services) => CallProxyServiceCollectionExtensions.WrapWithCallProxy<ICustomerStore>(services, _ => { });")]
    [InlineData("public static ICustomerStore Wrap(ICustomerStore store) => CallProxy.Create(store);")]
    [InlineData("public static ICustomerStore Wrap(ICustomerStore store) => SharedKernel.Testing.CallProxy.Create<ICustomerStore>(store, null);")]
    [InlineData("public static ICustomerStore Wrap(ICustomerStore store) => global::SharedKernel.Testing.CallProxy.Create<ICustomerStore>(store);")]
    [InlineData("public static void Stub(CallHooks<ICustomerStore> hooks) => hooks.EmailExists.Returns(false);")]
    [InlineData("public static void Stub(CallHooks<ICustomerStore> hooks) => hooks.Find.Before(_ => { }).After(_ => { });")]
    public void Finds_the_interface_of_every_way_to_wrap_or_hook_it(string member)
    {
        // Arrange
