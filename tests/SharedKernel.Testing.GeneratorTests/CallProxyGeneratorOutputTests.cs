    }

    [Fact]
    public void A_service_that_is_a_type_parameter_or_a_lookalike_method_generates_nothing()
    {
        // Arrange
        var source = CustomerStore + """
            public static class Setup
            {
                public static T Wrap<T>(T inner) where T : class => CallProxy.Create<T>(inner);

                public static ICustomerStore Create<T>(ICustomerStore store) => store;

                public static ICustomerStore Other(ICustomerStore store) => Create<ICustomerStore>(store);
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.Run(compilation);

        // Assert
        GeneratorTestHarness.GetHintNames(runResult).ShouldBeEmpty();
        GeneratorTestHarness.GetDiagnostics(runResult).ShouldBeEmpty();
    }

    [Fact]
    public void Interfaces_with_the_same_sanitized_name_get_distinct_files_and_classes()
    {
        // Arrange
        const string source = """
            namespace A.B
            {
                public interface IC { void Ping(); }
            }

            namespace A_B
            {
                public interface IC { void Pong(); }
            }

            public static class Setup
            {
                public static void Wrap(A.B.IC first, A_B.IC second)
                {
                    CallProxy.Create(first, hooks => hooks.Ping.Before(_ => { }));
                    CallProxy.Create(second, hooks => hooks.Pong.Before(_ => { }));
                }
            }
            """;

        // Act
        var diagnostics = GeneratorTestHarness.Compile(source, out var runResult);

        // Assert
        diagnostics.ShouldBeEmpty();
        GeneratorTestHarness.GetHintNames(runResult).ShouldBe(["CallProxy.A_B_IC.g.cs", "CallProxy.A_B_IC_2.g.cs"]);
    }

    [Fact]
    public void An_edit_elsewhere_reuses_the_cached_sites()
    {
        // Arrange
        var compilation = GeneratorTestHarness.CreateCompilation(CustomerStore + """
            public static class Setup
            {
                public static ICustomerStore Wrap(ICustomerStore store) => CallProxy.Create(store, hooks => hooks.EmailExists.Returns(false));
            }
            """);
        var options = (CSharpParseOptions)compilation.SyntaxTrees[0].Options;
        var driver = SharedHarness.CreateDriver([new CallProxyGenerator()], options, trackIncrementalGeneratorSteps: true)
            .RunGenerators(compilation, TestContext.Current.CancellationToken);
        var edited = compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText(
            "namespace Demo; public static class Unrelated { public static int Value => 1; }",
            options,
            cancellationToken: TestContext.Current.CancellationToken));

        // Act
        var runResult = driver.RunGenerators(edited, TestContext.Current.CancellationToken).GetRunResult();

        // Assert
        runResult.Results.ShouldHaveSingleItem().TrackedSteps["CallProxySites"]
            .SelectMany(static step => step.Outputs)
            .ShouldAllSatisfy(static output => output.Reason.ShouldBeOneOf(IncrementalStepRunReason.Cached, IncrementalStepRunReason.Unchanged));
    }
