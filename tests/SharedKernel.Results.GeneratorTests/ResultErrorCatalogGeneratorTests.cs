namespace SharedKernel.Results.GeneratorTests;

public sealed class ResultErrorCatalogGeneratorTests
{
    [Fact]
    public void Generates_error_catalog_for_static_error_provider_methods()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class UserErrors
            {
                public static Result NotFound(Guid id) => Result.NotFound($"User with id {id} was not found.");

                public static Result DuplicateEmail(string email) => Result.Conflict($"User with email '{email}' already exists.");

                public static Result InvalidEmail() => Result.Invalid(
                    detail: "Email is not valid.",
                    field: "Email",
                    message: "Email is invalid.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("// <auto-generated />", StringComparison.Ordinal);
        (generatedSource).ShouldContain("[assembly: SharedKernel.Results.ResultErrorCatalogProviderAttribute(typeof(SharedKernel.Results.", StringComparison.Ordinal);
        (generatedSource).ShouldContain("internal static class ResultErrorCatalogGenerated", StringComparison.Ordinal);
        (generatedSource).ShouldContain("public sealed class Generated", StringComparison.Ordinal);
        (generatedSource).ShouldContain("demo-usererrors-notfound", StringComparison.Ordinal);
        (generatedSource).ShouldContain("demo-usererrors-duplicateemail", StringComparison.Ordinal);
        (generatedSource).ShouldContain("demo-usererrors-invalidemail", StringComparison.Ordinal);
        (generatedSource).ShouldContain("docs/errors/README.md", StringComparison.Ordinal);
        (generatedSource).ShouldContain("ResultStatus.NotFound", StringComparison.Ordinal);
        (generatedSource).ShouldContain("ResultStatus.Conflict", StringComparison.Ordinal);
        (generatedSource).ShouldContain("ResultStatus.Invalid", StringComparison.Ordinal);
        (generatedSource).ShouldContain("\"not_found\"", StringComparison.Ordinal);
        (generatedSource).ShouldContain("\"conflict\"", StringComparison.Ordinal);
        (generatedSource).ShouldContain("\"invalid\"", StringComparison.Ordinal);
        (generatedSource).ShouldContain("User with id {id} was not found.", StringComparison.Ordinal);
        (generatedSource).ShouldContain("User with email '{email}' already exists.", StringComparison.Ordinal);
        (generatedSource).ShouldContain("Email is not valid.", StringComparison.Ordinal);
    }

    [Fact]
    public void Generates_error_catalog_for_result_error_factory_without_http_metadata()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class UserErrors
            {
                public static Result SaveFailed() => Result.Error("Save failed.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("ResultStatus.Error", StringComparison.Ordinal);
        (generatedSource).ShouldNotContain("HttpStatusCode", StringComparison.Ordinal);
        (generatedSource).ShouldContain("Code = \"error\"", StringComparison.Ordinal);
        (generatedSource).ShouldContain("DetailTemplate = \"Save failed.\"", StringComparison.Ordinal);
    }

    [Fact]
    public void Ignores_non_error_classes_and_non_result_members()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class UserMessages
            {
                public static string Greeting() => "hello";
            }

            public static class UserErrors
            {
                public static string Greeting() => "hello";
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        // Assert
        (runResult.Results.Single().GeneratedSources).ShouldBeEmpty();
    }

    [Fact]
    public void Generates_error_catalog_for_internal_error_providers_returning_generic_results()
    {
        // Arrange
        const string source = """
            namespace Demo;

            internal static class CsvErrors
            {
                internal static Result<string> MissingHeader(string columnName) => Result.Invalid<string>(
                    detail: $"Required column '{columnName}' is missing.",
                    field: "Headers",
                    message: "Required column is missing.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("demo-csverrors-missingheader", StringComparison.Ordinal);
        (generatedSource).ShouldContain("ResultStatus.Invalid", StringComparison.Ordinal);
        (generatedSource).ShouldContain("\"invalid\"", StringComparison.Ordinal);
        (generatedSource).ShouldContain("Required column '{columnName}' is missing.", StringComparison.Ordinal);
    }

    [Fact]
    public void Generates_error_catalog_for_static_properties()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class SystemErrors
            {
                public static Result DatabaseUnavailable => Result.Unavailable("Database is unavailable.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("demo-systemerrors-databaseunavailable", StringComparison.Ordinal);
        (generatedSource).ShouldContain("ResultStatus.Unavailable", StringComparison.Ordinal);
        (generatedSource).ShouldContain("Database is unavailable.", StringComparison.Ordinal);
    }

    [Fact]
    public void Adds_parameter_type_suffix_to_overloaded_method_identifiers()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class UserErrors
            {
                public static Result NotFound(Guid id) => Result.NotFound($"User {id} was not found.");

                public static Result NotFound(string email) => Result.NotFound($"User {email} was not found.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("demo-usererrors-notfound-guid", StringComparison.Ordinal);
        (generatedSource).ShouldContain("demo-usererrors-notfound-string", StringComparison.Ordinal);
    }

    [Fact]
    public void Preserves_interpolated_template_format_clauses()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class TourErrors
            {
                public static Result StartDateInPast(DateTime startDate) =>
                    Result.Invalid($"Start date {startDate:yyyy-MM-dd} cannot be in the past.", "StartDate", "Start date is invalid.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("Start date {startDate:yyyy-MM-dd} cannot be in the past.", StringComparison.Ordinal);
    }

    [Fact]
    public void Escapes_generated_string_literals()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class FileErrors
            {
                public static Result InvalidPath() => Result.Invalid(
                    "Path \"C:\\\\Temp\" is invalid.\nChoose another path.",
                    "Path",
                    "Path is invalid.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);
        var generatedSource = GeneratorTestHarness.GetGeneratedSource(runResult);

        // Assert
        (generatedSource).ShouldContain("Path \\\"C:\\\\\\\\Temp\\\" is invalid.\\nChoose another path.", StringComparison.Ordinal);
    }

    [Fact]
    public void Ignores_unsupported_result_member_shapes()
    {
        // Arrange
        const string source = """
            namespace Demo;

            public static class UserErrors
            {
                public static Result MissingExpressionBody()
                {
                    var detail = "User was not found.";
                    return Result.NotFound(detail);
                }

                public static Result Success() => Result.Success();

                public static Result Wrapped() => CreateNotFound();

                private static Result CreateNotFound() => Result.NotFound("User was not found.");
            }
            """;
        var compilation = GeneratorTestHarness.CreateCompilation(source);

        // Act
        var runResult = GeneratorTestHarness.RunGeneratorDriver(compilation);

        // Assert
        (runResult.Results.Single().GeneratedSources).ShouldBeEmpty();
    }
}
