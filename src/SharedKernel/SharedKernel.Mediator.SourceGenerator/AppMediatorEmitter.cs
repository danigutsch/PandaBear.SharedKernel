            .Where(static handler => handler.IsAccessibleToGeneratedMediator && handler.HasCompatibleHandleMethod)
            .ToArray();
        var requestNameLiteral = MediatorGenerationNames.EscapeStringLiteral(streamRequest.Name);
        var assemblyNameLiteral = MediatorGenerationNames.EscapeStringLiteral(streamRequest.AssemblyName);

        builder.AppendLine();
        GeneratedXmlDocumentationEmitter.AppendSummary(
            builder,
            "    ",
            $"Sends a <see cref=\"{streamRequest.MetadataName}\"/> stream through the generated mediator dispatch path.");
        GeneratedXmlDocumentationEmitter.AppendParam(
            builder,
            "    ",
            "request",
            "The stream request instance to dispatch.");
        GeneratedXmlDocumentationEmitter.AppendParam(
            builder,
            "    ",
            "ct",
            "The cancellation token for the operation.");
        GeneratedXmlDocumentationEmitter.AppendReturns(
            builder,
            "    ",
            "The produced response stream.");
        builder.Append("    public global::System.Collections.Generic.IAsyncEnumerable<")
            .Append(streamRequest.ItemResponse.MetadataName)
            .Append("> Send(")
            .Append(streamRequest.MetadataName)
            .AppendLine(" request,");
        builder.AppendLine("        global::System.Threading.CancellationToken ct)");
        builder.AppendLine("    {");
        builder.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(request);");
        builder.AppendLine();

        switch (accessibleHandlers.Length)
        {
            case 0:
                builder.Append("        return GeneratedDispatch.ThrowNoStreamHandler<")
                    .Append(streamRequest.ItemResponse.MetadataName)
                    .AppendLine(">(request);");
                break;
            case 1:
                builder.Append("        return SendStream_")
                    .Append(streamRequestIndex.ToString("D4", CultureInfo.InvariantCulture))
                    .AppendLine("(request, ct);");
                break;
            default:
                builder.Append("        return GeneratedDispatch.ThrowAmbiguousStreamHandlers<")
                    .Append(streamRequest.ItemResponse.MetadataName)
                    .Append(">(request, ")
                    .Append(accessibleHandlers.Length.ToString(CultureInfo.InvariantCulture))
                    .AppendLine(");");
                break;
        }

        builder.AppendLine("    }");

        if (accessibleHandlers.Length == 1)
        {
            EmitStreamSendHelper(builder, streamRequest, streamRequestIndex, requestNameLiteral, assemblyNameLiteral, accessibleHandlers[0]);
        }
    }

    private static void EmitStreamSendHelper(
        StringBuilder builder,
        StreamRequestDescriptor streamRequest,
        int streamRequestIndex,
        string requestNameLiteral,
        string assemblyNameLiteral,
        StreamHandlerDescriptor handlerDescriptor)
    {
        builder.AppendLine();
        builder.Append("    private async global::System.Collections.Generic.IAsyncEnumerable<")
            .Append(streamRequest.ItemResponse.MetadataName)
            .Append("> SendStream_")
            .Append(streamRequestIndex.ToString("D4", CultureInfo.InvariantCulture))
            .Append('(')
            .Append(streamRequest.MetadataName)
            .AppendLine(" request,");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken ct)");
        builder.AppendLine("    {");
        builder.AppendLine("        var activity = _instrumentation.ActivitySource.StartActivity(global::SharedKernel.Mediator.MediatorTelemetry.ActivityStream, global::System.Diagnostics.ActivityKind.Internal);");
        builder.Append("        activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagRequestName, ")
            .Append(requestNameLiteral)
            .AppendLine(");");
        builder.Append("        activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagRequestAssembly, ")
            .Append(assemblyNameLiteral)
            .AppendLine(");");
        builder.Append("        activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagHandlerName, ")
            .Append(MediatorGenerationNames.EscapeStringLiteral(GetSimpleName(handlerDescriptor.MetadataName)))
            .AppendLine(");");
        builder.AppendLine("        var outcome = global::SharedKernel.Mediator.MediatorTelemetry.OutcomeSuccess;");
        if (streamRequest.Pipelines.Length == 0)
        {
            builder.Append("        var enumerator = StreamHandler_")
                .Append(streamRequestIndex.ToString("D4", CultureInfo.InvariantCulture))
                .AppendLine(".Handle(request, ct).GetAsyncEnumerator(ct);");
        }
        else
        {
            builder.Append("        var enumerator = GeneratedPipelines.")
                .Append(GetGeneratedPipelineMethodName(streamRequest.Pipelines[0].IsStream, streamRequestIndex))
                .AppendLine("(this, request, ct).GetAsyncEnumerator(ct);");
        }

        // yield return cannot live in a try-with-catch, only in try-finally.
        // Inner try-catches handle MoveNextAsync errors; yield return lives in the outer try-finally.
        builder.AppendLine("        try");
        builder.AppendLine("        {");
        builder.AppendLine("            while (true)");
        builder.AppendLine("            {");
        builder.AppendLine("                bool hasNext;");
        builder.AppendLine("                try");
        builder.AppendLine("                {");
        builder.AppendLine("                    hasNext = await enumerator.MoveNextAsync();");
        builder.AppendLine("                }");
        builder.AppendLine("                catch (global::System.OperationCanceledException)");
        builder.AppendLine("                {");
        builder.AppendLine("                    outcome = global::SharedKernel.Mediator.MediatorTelemetry.OutcomeCancelled;");
        builder.AppendLine("                    activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagOutcome, global::SharedKernel.Mediator.MediatorTelemetry.OutcomeCancelled);");
        builder.AppendLine("                    throw;");
        builder.AppendLine("                }");
        builder.AppendLine("                catch (global::System.Exception ex)");
        builder.AppendLine("                {");
        builder.AppendLine("                    outcome = global::SharedKernel.Mediator.MediatorTelemetry.OutcomeError;");
        builder.AppendLine("                    activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagErrorType, ex.GetType().Name);");
        builder.AppendLine("                    activity?.AddException(ex);");
        builder.AppendLine("                    activity?.SetStatus(global::System.Diagnostics.ActivityStatusCode.Error, ex.Message);");
        builder.AppendLine("                    activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagOutcome, global::SharedKernel.Mediator.MediatorTelemetry.OutcomeError);");
        builder.AppendLine("                    throw;");
        builder.AppendLine("                }");
        builder.AppendLine("                if (!hasNext)");
        builder.AppendLine("                {");
        builder.AppendLine("                    activity?.SetTag(global::SharedKernel.Mediator.MediatorTelemetry.TagOutcome, global::SharedKernel.Mediator.MediatorTelemetry.OutcomeSuccess);");
        builder.AppendLine("                    activity?.SetStatus(global::System.Diagnostics.ActivityStatusCode.Ok);");
        builder.AppendLine("                    break;");
        builder.AppendLine("                }");
        builder.AppendLine("                yield return enumerator.Current;");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");
        builder.AppendLine("            await enumerator.DisposeAsync();");
        builder.AppendLine("            activity?.Dispose();");
        builder.Append("            _instrumentation.StreamsTotal.Add(1, new global::System.Diagnostics.TagList { { global::SharedKernel.Mediator.MediatorTelemetry.TagRequestName, ")
            .Append(requestNameLiteral)
            .AppendLine(" }, { global::SharedKernel.Mediator.MediatorTelemetry.TagOutcome, outcome } });");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitConstructorParameters(StringBuilder builder, DiscoveryModel model)
    {
        for (var requestIndex = 0; requestIndex < model.Requests.Length; requestIndex++)
        {
            var request = model.Requests[requestIndex];
            var handlers = request.Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator && handler.HasCompatibleHandleMethod).ToArray();
            if (handlers.Length == 1)
            {
                builder.Append("        ").Append(handlers[0].MetadataName).Append(" requestHandler").Append(requestIndex.ToString("D4", CultureInfo.InvariantCulture)).AppendLine(",");
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    builder.Append("        ").Append(request.Pipelines[pipelineIndex].MetadataName).Append(" requestPipeline")
                        .Append(requestIndex.ToString("D4", CultureInfo.InvariantCulture)).Append(pipelineIndex.ToString("D4", CultureInfo.InvariantCulture)).AppendLine(",");
                }
            }
        }

        for (var streamIndex = 0; streamIndex < model.StreamRequests.Length; streamIndex++)
        {
            var request = model.StreamRequests[streamIndex];
            var handlers = request.Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator).ToArray();
            if (handlers.Length == 1)
            {
                builder.Append("        ").Append(handlers[0].MetadataName).Append(" streamHandler").Append(streamIndex.ToString("D4", CultureInfo.InvariantCulture)).AppendLine(",");
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    builder.Append("        ").Append(request.Pipelines[pipelineIndex].MetadataName).Append(" streamPipeline")
                        .Append(streamIndex.ToString("D4", CultureInfo.InvariantCulture)).Append(pipelineIndex.ToString("D4", CultureInfo.InvariantCulture)).AppendLine(",");
                }
            }
        }

        for (var notificationIndex = 0; notificationIndex < model.Notifications.Length; notificationIndex++)
        {
            var handlers = model.Notifications[notificationIndex].Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator).ToArray();
            for (var handlerIndex = 0; handlerIndex < handlers.Length; handlerIndex++)
            {
                builder.Append("        ").Append(handlers[handlerIndex].MetadataName).Append(" notificationHandler")
                    .Append(notificationIndex.ToString("D4", CultureInfo.InvariantCulture)).Append(handlerIndex.ToString("D4", CultureInfo.InvariantCulture)).AppendLine(",");
            }
        }
    }

    private static void EmitConstructorAssignments(StringBuilder builder, DiscoveryModel model)
    {
        for (var requestIndex = 0; requestIndex < model.Requests.Length; requestIndex++)
        {
            var request = model.Requests[requestIndex];
            if (request.Handlers.Count(static handler => handler.IsAccessibleToGeneratedMediator && handler.HasCompatibleHandleMethod) == 1)
            {
                EmitAssignment(builder, "RequestHandler_" + requestIndex.ToString("D4", CultureInfo.InvariantCulture), "requestHandler" + requestIndex.ToString("D4", CultureInfo.InvariantCulture));
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    EmitAssignment(builder,
                        "RequestPipeline_" + requestIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture),
                        "requestPipeline" + requestIndex.ToString("D4", CultureInfo.InvariantCulture) + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture));
                }
            }
        }

        for (var streamIndex = 0; streamIndex < model.StreamRequests.Length; streamIndex++)
        {
            var request = model.StreamRequests[streamIndex];
            if (request.Handlers.Count(static handler => handler.IsAccessibleToGeneratedMediator) == 1)
            {
                EmitAssignment(builder, "StreamHandler_" + streamIndex.ToString("D4", CultureInfo.InvariantCulture), "streamHandler" + streamIndex.ToString("D4", CultureInfo.InvariantCulture));
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    EmitAssignment(builder,
                        "StreamPipeline_" + streamIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture),
                        "streamPipeline" + streamIndex.ToString("D4", CultureInfo.InvariantCulture) + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture));
                }
            }
        }

        for (var notificationIndex = 0; notificationIndex < model.Notifications.Length; notificationIndex++)
        {
            var handlers = model.Notifications[notificationIndex].Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator).ToArray();
            for (var handlerIndex = 0; handlerIndex < handlers.Length; handlerIndex++)
            {
                EmitAssignment(builder,
                    "NotificationHandler_" + notificationIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + handlerIndex.ToString("D4", CultureInfo.InvariantCulture),
                    "notificationHandler" + notificationIndex.ToString("D4", CultureInfo.InvariantCulture) + handlerIndex.ToString("D4", CultureInfo.InvariantCulture));
            }
        }
    }

    private static void EmitDependencyProperties(StringBuilder builder, DiscoveryModel model)
    {
        for (var requestIndex = 0; requestIndex < model.Requests.Length; requestIndex++)
        {
            var request = model.Requests[requestIndex];
            var handlers = request.Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator && handler.HasCompatibleHandleMethod).ToArray();
            if (handlers.Length == 1)
            {
                EmitProperty(builder, handlers[0].MetadataName, "RequestHandler_" + requestIndex.ToString("D4", CultureInfo.InvariantCulture));
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    EmitProperty(builder, request.Pipelines[pipelineIndex].MetadataName,
                        "RequestPipeline_" + requestIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture));
                }
            }
        }

        for (var streamIndex = 0; streamIndex < model.StreamRequests.Length; streamIndex++)
        {
            var request = model.StreamRequests[streamIndex];
            var handlers = request.Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator).ToArray();
            if (handlers.Length == 1)
            {
                EmitProperty(builder, handlers[0].MetadataName, "StreamHandler_" + streamIndex.ToString("D4", CultureInfo.InvariantCulture));
                for (var pipelineIndex = 0; pipelineIndex < request.Pipelines.Length; pipelineIndex++)
                {
                    EmitProperty(builder, request.Pipelines[pipelineIndex].MetadataName,
                        "StreamPipeline_" + streamIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + pipelineIndex.ToString("D4", CultureInfo.InvariantCulture));
                }
            }
        }

        for (var notificationIndex = 0; notificationIndex < model.Notifications.Length; notificationIndex++)
        {
            var handlers = model.Notifications[notificationIndex].Handlers.Where(static handler => handler.IsAccessibleToGeneratedMediator).ToArray();
            for (var handlerIndex = 0; handlerIndex < handlers.Length; handlerIndex++)
            {
                EmitProperty(builder, handlers[handlerIndex].MetadataName,
                    "NotificationHandler_" + notificationIndex.ToString("D4", CultureInfo.InvariantCulture) + "_" + handlerIndex.ToString("D4", CultureInfo.InvariantCulture));
            }
        }
    }

    private static void EmitAssignment(StringBuilder builder, string propertyName, string parameterName)
    {
        builder.Append("        global::System.ArgumentNullException.ThrowIfNull(").Append(parameterName).AppendLine(");");
        builder.Append("        ").Append(propertyName).Append(" = ").Append(parameterName).AppendLine(";");
    }

    private static void EmitProperty(StringBuilder builder, string typeName, string propertyName)
    {
        builder.AppendLine();
        builder.Append("    internal ").Append(typeName).Append(' ').Append(propertyName).AppendLine(" { get; }");
    }

    private static string GetGeneratedPipelineMethodName(bool isStream, int index)
    {
        return (isStream ? "InvokeStream_" : "Invoke_")
            + index.ToString("D4", CultureInfo.InvariantCulture);
    }

    private static string GetSimpleName(string metadataName)
    {
        var lastDotIndex = metadataName.LastIndexOf('.');
        return lastDotIndex >= 0 ? metadataName.Substring(lastDotIndex + 1) : metadataName;
    }
}
