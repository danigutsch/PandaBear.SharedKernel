using System.Text.Json.Serialization;
using System.Text.Json;

namespace PandaBear.AI;

/// <summary>Chat completion request body sent to the LiteLLM proxy.</summary>
/// <param name="Model">Name of the model the proxy routes the request to.</param>
/// <param name="Messages">Conversation messages that make up the prompt.</param>
/// <param name="ResponseFormat">Structured-output format the model response must follow.</param>
internal sealed record LiteLlmChatCompletionRequest(
    string Model,
    IReadOnlyList<LiteLlmMessage> Messages,
    [property: JsonPropertyName("response_format")] LiteLlmResponseFormat ResponseFormat);

/// <summary>Single chat message made of one or more content parts.</summary>
/// <param name="Role">Author role of the message, such as system or user.</param>
/// <param name="Content">Text and image parts that carry the message payload.</param>
internal sealed record LiteLlmMessage(string Role, IReadOnlyList<LiteLlmContentPart> Content);

/// <summary>One text or image part of a chat message.</summary>
/// <param name="Type">Part kind discriminator, such as text or image_url.</param>
/// <param name="Text">Text payload, set only for text parts.</param>
/// <param name="ImageUrl">Image reference, set only for image parts.</param>
internal sealed record LiteLlmContentPart(
    string Type,
    string? Text,
    [property: JsonPropertyName("image_url")] LiteLlmImageUrl? ImageUrl);

/// <summary>Image reference carried by an image content part.</summary>
/// <param name="Url">HTTP or data URL the model reads the image from.</param>
internal sealed record LiteLlmImageUrl(string Url);

/// <summary>Structured-output format requested from the model.</summary>
/// <param name="Type">Response format kind, such as json_schema.</param>
/// <param name="JsonSchema">Schema definition the response must satisfy.</param>
internal sealed record LiteLlmResponseFormat(
    string Type,
    [property: JsonPropertyName("json_schema")] LiteLlmJsonSchema JsonSchema);

/// <summary>Named JSON schema used to constrain model output.</summary>
/// <param name="Name">Identifier of the schema.</param>
/// <param name="Schema">Schema body describing the expected object.</param>
/// <param name="Strict">Whether the model must follow the schema exactly.</param>
internal sealed record LiteLlmJsonSchema(string Name, LiteLlmSchema Schema, bool Strict);

/// <summary>Object schema describing the expected response fields.</summary>
/// <param name="Type">JSON schema type of the root value, normally object.</param>
/// <param name="Properties">Schema of each expected field keyed by field name.</param>
/// <param name="Required">Names of fields the response must contain.</param>
/// <param name="AdditionalProperties">Whether fields not listed in the schema are allowed.</param>
internal sealed record LiteLlmSchema(
    string Type,
    IReadOnlyDictionary<string, LiteLlmSchemaProperty> Properties,
    IReadOnlyList<string> Required,
    bool AdditionalProperties);

/// <summary>Schema of a single response field.</summary>
internal sealed record LiteLlmSchemaProperty
{
    /// <summary>Creates a schema property with a single JSON schema type.</summary>
    public LiteLlmSchemaProperty(string type)
    {
        Type = type;
    }

    /// <summary>Creates a schema property that accepts any of several JSON schema types.</summary>
    public LiteLlmSchemaProperty(IReadOnlyList<string> type)
    {
        Type = type;
    }

    /// <summary>JSON schema type name, or a list of type names for nullable fields.</summary>
    public object Type
    {
        get;
    }
}

/// <summary>Chat completion response returned by the LiteLLM proxy.</summary>
/// <param name="Choices">Completion candidates produced by the model.</param>
internal sealed record LiteLlmChatCompletionResponse(IReadOnlyList<LiteLlmChoice> Choices);

/// <summary>One completion candidate.</summary>
/// <param name="Message">Message generated by the model.</param>
internal sealed record LiteLlmChoice(LiteLlmResponseMessage Message);

/// <summary>Message generated by the model.</summary>
/// <param name="Content">Generated text, or null when the model returned none.</param>
internal sealed record LiteLlmResponseMessage(string? Content);

/// <summary>Alt text and caption the model generated for an image.</summary>
/// <param name="AltText">Short description of the image for assistive technology.</param>
/// <param name="Caption">Optional visible caption, or null when none applies.</param>
internal sealed record GeneratedImageText(string AltText, string? Caption);

/// <summary>Source-generated JSON serialization context for the LiteLLM request and response models, so serialization stays trim and AOT safe.</summary>
[JsonSourceGenerationOptions(JsonSerializerDefaults.Web)]
[JsonSerializable(typeof(LiteLlmChatCompletionRequest))]
[JsonSerializable(typeof(LiteLlmChatCompletionResponse))]
[JsonSerializable(typeof(GeneratedImageText))]
internal sealed partial class LiteLlmJsonContext : JsonSerializerContext;
