namespace PandaBear.InputNormalization;

/// <summary>
/// Unicode character properties that .NET does not expose, for the contexts in which <see cref="PrintableText"/> keeps a
/// zero width joiner or non-joiner. The ranges are taken from the Unicode Character Database 18.0: emoji-data.txt
/// (Extended_Pictographic and Emoji_Modifier), extracted/DerivedJoiningType.txt (Joining_Type), and
/// extracted/DerivedCombiningClass.txt (Canonical_Combining_Class=Virama, the value 9).
/// </summary>
internal static class UnicodeProperties
{
    /// <summary>Returns whether the code point has the property Extended_Pictographic.</summary>
    /// <param name="codePoint">Code point.</param>
    /// <returns><see langword="true"/> when the code point is an emoji or a pictograph reserved for emoji.</returns>
    public static bool IsExtendedPictographic(int codePoint) => InRanges(ExtendedPictographicRanges, codePoint);

    /// <summary>Returns whether the code point is an emoji modifier, a skin tone U+1F3FB to U+1F3FF.</summary>
    /// <param name="codePoint">Code point.</param>
    /// <returns><see langword="true"/> when the code point has the property Emoji_Modifier.</returns>
    public static bool IsEmojiModifier(int codePoint) => codePoint is >= 0x1F3FB and <= 0x1F3FF;

    /// <summary>Returns whether the code point joins to the character after it: Joining_Type Dual_Joining or Left_Joining.</summary>
    /// <param name="codePoint">Code point.</param>
    /// <returns><see langword="true"/> when the code point is in the class <c>$LJ</c> of UTS #39 condition A1.</returns>
    public static bool IsLeftJoining(int codePoint) => InRanges(LeftJoiningRanges, codePoint);

    /// <summary>Returns whether the code point joins to the character before it: Joining_Type Dual_Joining or Right_Joining.</summary>
    /// <param name="codePoint">Code point.</param>
    /// <returns><see langword="true"/> when the code point is in the class <c>$RJ</c> of UTS #39 condition A1.</returns>
    public static bool IsRightJoining(int codePoint) => InRanges(RightJoiningRanges, codePoint);

    /// <summary>Returns whether the code point is a virama: Canonical_Combining_Class=Virama.</summary>
    /// <param name="codePoint">Code point.</param>
    /// <returns><see langword="true"/> when the code point is in the class <c>$V</c> of UTS #39 conditions A2 and B.</returns>
    public static bool IsVirama(int codePoint) => InRanges(ViramaRanges, codePoint);

    // Each table holds sorted, disjoint, inclusive ranges as pairs of first and last code point.
    private static bool InRanges(ReadOnlySpan<int> ranges, int codePoint)
    {
        int low = 0;
        int high = (ranges.Length / 2) - 1;
        while (low <= high)
        {
            int middle = low + ((high - low) / 2);
            if (codePoint < ranges[2 * middle])
            {
                high = middle - 1;
            }
            else if (codePoint > ranges[(2 * middle) + 1])
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }

