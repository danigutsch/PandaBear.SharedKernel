using System.Globalization;
using System.Text;

namespace SharedKernel.Testing.SourceGenerator;

/// <summary>Writes the source of one generated proxy: the typed hooks, the call types, the hooks holder, and the proxy class.</summary>
internal static class ProxyEmitter
{
    private const string Hooks = "global::SharedKernel.Testing.CallHooks";
    private const string MethodHooks = "global::SharedKernel.Testing.MethodHooks";
    private const string GeneratedHooks = "global::SharedKernel.Testing.GeneratedCallHooks";

    /// <summary>Writes the source.</summary>
    /// <param name="model">The proxy to generate.</param>
    /// <param name="containerName">The name of the generated static class, unique in the compilation.</param>
    /// <returns>The C# source.</returns>
    public static string Emit(ProxyModel model, string containerName)
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated />\n");
        builder.Append("#nullable enable\n\n");
        builder.Append("namespace SharedKernel.Testing\n{\n");
        builder.Append("    /// <summary>The typed CallProxy hooks and proxy generated for <c>").Append(Xml(model.Display)).Append("</c>.</summary>\n");
        builder.Append("    internal static class ").Append(containerName).Append("\n    {\n");
        WriteHookMembers(builder, model);
        WriteRegistration(builder, model);
        foreach (var method in model.Methods)
        {
            WriteCallType(builder, method);
        }

        WriteHookSet(builder, model);
        WriteProxy(builder, model);
        builder.Append("    }\n}\n");
        return builder.ToString();
    }

    private static void WriteHookMembers(StringBuilder builder, ProxyModel model)
    {
        if (model.Methods.Count == 0)
        {
            return;
        }

        builder.Append("        extension(").Append(Hooks).Append('<').Append(model.ServiceType).Append("> hooks)\n        {\n");
        for (var index = 0; index < model.Methods.Count; index++)
        {
            var method = model.Methods[index];
            if (index > 0)
            {
                builder.Append('\n');
            }

            builder.Append("            /// <summary>Gets the hooks of <c>").Append(Xml(method.Display)).Append("</c>.</summary>\n");
            builder.Append("            public ").Append(HooksType(method)).Append(' ').Append(method.HookName)
                .Append(" => hooks.Generated<HookSet>().").Append(FieldName(index)).Append(";\n");
        }

        builder.Append("        }\n\n");
    }

    private static void WriteRegistration(StringBuilder builder, ProxyModel model)
    {
        builder.Append("        /// <summary>Registers the generated hooks, so a proxy without hooks can be created too.</summary>\n");
        builder.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
        builder.Append("        internal static void Register() => global::SharedKernel.Testing.CallProxy.Register<")
            .Append(model.ServiceType).Append(">(static () => new HookSet());\n");
    }

    private static void WriteCallType(StringBuilder builder, ProxyMethod method)
    {
        builder.Append("\n        /// <summary>One call of <c>").Append(Xml(method.Display)).Append("</c>.</summary>\n");
        builder.Append("        internal sealed class ").Append(method.CallTypeName).Append("\n        {\n");
        builder.Append("            internal ").Append(method.CallTypeName).Append('(')
            .Append(string.Join(", ", method.Parameters.Select(static parameter => parameter.Type + " " + parameter.Name))).Append(")\n");
        builder.Append("            {\n");
        foreach (var parameter in method.Parameters)
        {
            builder.Append("                ").Append(parameter.PropertyName).Append(" = ").Append(parameter.Name).Append(";\n");
        }

        builder.Append("            }\n");
        foreach (var parameter in method.Parameters)
        {
            builder.Append("\n            /// <summary>Gets the <c>").Append(Xml(parameter.RawName)).Append("</c> argument.</summary>\n");
            builder.Append("            public ").Append(parameter.Type).Append(' ').Append(parameter.PropertyName).Append(" { get; }\n");
        }

        if (method.ResultType is not null)
        {
            builder.Append("\n            /// <summary>Gets the result; set before the after hooks run.</summary>\n");
            builder.Append("            public ").Append(method.ResultType).Append(" Result { get; internal set; } = default!;\n");
        }

        builder.Append("        }\n");
    }

    private static void WriteHookSet(StringBuilder builder, ProxyModel model)
    {
        builder.Append("\n        /// <summary>The hooks of every method of <c>").Append(Xml(model.Display)).Append("</c>.</summary>\n");
        builder.Append("        internal sealed class HookSet : ").Append(GeneratedHooks).Append('<').Append(model.ServiceType).Append(">\n        {\n");
        for (var index = 0; index < model.Methods.Count; index++)
        {
            var method = model.Methods[index];
            builder.Append("            internal readonly ").Append(HooksType(method)).Append(' ').Append(FieldName(index)).Append(" = new();\n\n");
        }

        builder.Append("            /// <inheritdoc />\n");
        builder.Append("            protected override ").Append(model.ServiceType).Append(" Wrap(").Append(model.ServiceType)
            .Append(" inner) => new Proxy(inner, this);\n");
        builder.Append("        }\n");
    }

    private static void WriteProxy(StringBuilder builder, ProxyModel model)
    {
        builder.Append("\n        private sealed class Proxy : ").Append(model.ServiceType).Append("\n        {\n");
        builder.Append("            private readonly ").Append(model.ServiceType).Append(" __inner;\n");
        builder.Append("            private readonly HookSet __hooks;\n\n");
        builder.Append("            internal Proxy(").Append(model.ServiceType).Append(" inner, HookSet hooks)\n");
        builder.Append("            {\n");
        builder.Append("                __inner = inner;\n");
        builder.Append("                __hooks = hooks;\n");
        builder.Append("            }\n");
        for (var index = 0; index < model.Methods.Count; index++)
        {
            WriteProxyMethod(builder, model.Methods[index], FieldName(index));
        }

        builder.Append("        }\n");
    }

    private static void WriteProxyMethod(StringBuilder builder, ProxyMethod method, string field)
    {
        var isAsync = method.ReturnKind is not (ProxyReturnKind.Void or ProxyReturnKind.Value);
        var hooks = "__hooks." + field;
        var arguments = string.Join(", ", method.Parameters.Select(static parameter => parameter.Name));
        var inner = (method.CastInner ? "((" + method.DeclaringType + ")__inner)" : "__inner") + "." + method.MethodName + "(" + arguments + ")";
        var wait = isAsync ? ".ConfigureAwait(false);\n" : ".GetAwaiter().GetResult();\n";
        var awaitKeyword = isAsync ? "await " : string.Empty;

        builder.Append("\n            ").Append(method.ReturnAttributes).Append(isAsync ? "async " : string.Empty)
            .Append(method.ReturnType).Append(' ').Append(method.DeclaringType).Append('.').Append(method.MethodName).Append('(')
            .Append(string.Join(", ", method.Parameters.Select(static parameter => parameter.Modifiers + parameter.Type + " " + parameter.Name)))
            .Append(")\n");
        builder.Append("            {\n");
        builder.Append("                var __call = new ").Append(method.CallTypeName).Append('(').Append(arguments).Append(");\n");
        builder.Append("                ").Append(awaitKeyword).Append(hooks).Append(".RunBefore(__call)").Append(wait);
        if (method.ResultType is null)
        {
            builder.Append("                ").Append(awaitKeyword).Append(inner).Append(isAsync ? ".ConfigureAwait(false);\n" : ";\n");
        }
        else
        {
            builder.Append("                __call.Result = ").Append(hooks).Append(".TryGetReplacement(out var __replacement)\n");
            builder.Append("                    ? __replacement\n");
            builder.Append("                    : ").Append(awaitKeyword).Append(inner).Append(isAsync ? ".ConfigureAwait(false);\n" : ";\n");
        }

        builder.Append("                ").Append(awaitKeyword).Append(hooks).Append(".RunAfter(__call)").Append(wait);
        if (method.ResultType is not null)
        {
            builder.Append("                return __call.Result;\n");
        }

        builder.Append("            }\n");
    }

    private static string HooksType(ProxyMethod method) =>
        method.ResultType is null
            ? MethodHooks + "<" + method.CallTypeName + ">"
            : MethodHooks + "<" + method.CallTypeName + ", " + method.ResultType + ">";

    private static string FieldName(int index) => "Hooks" + index.ToString(CultureInfo.InvariantCulture);

    private static string Xml(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
